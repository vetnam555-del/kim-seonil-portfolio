/**
 * 아카이브 등급 뒤에 오는 꼬리 순서.
 *
 * 앞부분(대표 사례)은 여기 적지 않는다 — edition.spreadOrder 가 정한다.
 * 아카이브 등급은 항상 체인 맨 끝에 둔다: 배열 순서를 그대로 썼을 때 대표 사례 바로 다음이
 * 근거가 얇은 아카이브 페이지로 뚝 떨어지는 문제를 막는다.
 */
export const solutionTailOrder = ["jestina", "daekyo", "gangwon", "automation", "edith"];

/**
 * 케이스 정렬 기준 — 판이 정한 읽는 순서 + 꼬리.
 *
 * 세 곳이 이 배열을 쓴다: 홈의 '그 외 케이스' 목록, 이력서의 대표 프로젝트 정렬,
 * 상세 페이지의 '다음 프로젝트' 이동. 세 곳이 한 배열을 쓰는 것은 원래 의도였는데,
 * 그 배열이 판과 무관한 고정값이어서 홈의 CH 번호와만 어긋나 있었다.
 * spreadOrder 에서 파생시키면 세 곳이 전부 판별 순서를 따른다.
 * spreadOrder 에 없고 꼬리에도 없는 슬러그는 꼬리 뒤로 밀린다.
 */
export const solutionOrder = [
  ...edition.spreadOrder,
  ...solutionTailOrder.filter((s) => !edition.spreadOrder.includes(s)),
];

/**
 * 케이스 상세의 "다음 프로젝트" 이동.
 *
 * ── 고정 배열을 버린 이유 (2026.08.18)
 * 예전에는 solutionOrder = [dyson, jestina, daekyo, newbalance, …] 라는 **판과 무관한 고정 배열**을
 * 썼다. 그런데 홈은 케이스에 CH.01~CH.05 번호를 붙이고, 그 번호는 판마다 다른
 * edition.spreadOrder 를 따른다. 두 순서가 어긋나면 이동이 이렇게 된다 —
 *
 *   일반판(jestina → newbalance → daekyo → dyson):
 *     CH.01 제이에스티나에서 '다음'을 누르면 CH.03 대교로 건너뛰고,
 *     CH.03 대교에서 누르면 CH.02 뉴발란스로 **되돌아가고**,
 *     CH.04 다이슨에서 누르면 CH.01 로 돌아온다.
 *
 * 홈의 다리 문장(BRIDGES)은 이미 spreadOrder 를 따라 "다음 케이스가 답할 질문"을 던진다.
 * 그러니까 같은 사이트가 '다음'에 대해 두 가지 답을 하고 있었다.
 * 읽는 순서를 정한 곳이 한 곳(spreadOrder)이면 이동도 그것을 따라야 한다.
 */
export function getNextProject(current: Project): Project {
  /* solutionOrder 에 없는 슬러그는 맨 뒤로 — indexOf 의 -1 이 앞으로 튀는 것을 막는다 */
  const rank = (slug: string) => {
    const i = solutionOrder.indexOf(slug);
    return i >= 0 ? i : solutionOrder.length;
  };
  const nonArchive = projects
    .filter((p) => p.tier !== "archive")
    .sort((a, b) => rank(a.slug) - rank(b.slug));
  const archive = projects.filter((p) => p.tier === "archive");
  const chain = [...nonArchive, ...archive];
  const idx = chain.findIndex((p) => p.slug === current.slug);
  return chain[(idx + 1) % chain.length];
}
